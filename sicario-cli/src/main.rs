/// `sicario policy validate` — parse `.sicario/policy.yaml` and check all rule
/// IDs against the loaded rule set. Prints unknown rule IDs and invalid glob
/// patterns. Exits 0 if valid, exits 1 if any issues found.
fn cmd_policy_validate(args: cli::policy::PolicyValidateArgs) -> Result<ExitCode> {
    use engine::sast_engine::SastEngine;

    let project_root = PathBuf::from(&args.dir);
    let policy_path = project_root.join(".sicario").join("policy.yaml");

    if !policy_path.exists() {
        eprintln!(
            "sicario: No policy file found at '{}'.",
            policy_path.display()
        );
        return Ok(ExitCode::FindingsDetected);
    }

    // Parse the policy file
    let policy = match policy::PolicyLoader::load(&project_root) {
        Ok(Some(p)) => p,
        Ok(None) => {
            eprintln!("sicario: No policy file found.");
            return Ok(ExitCode::FindingsDetected);
        }
        Err(e) => {
            eprintln!("sicario: Failed to parse policy file: {e}");
            return Ok(ExitCode::FindingsDetected);
        }
    };

    // Load the rule set to validate rule IDs against
    let mut eng = SastEngine::new(&project_root)?;
    load_embedded_rules_into(&mut eng);
    if eng.get_rules().is_empty() {
        let disk_files = discover_bundled_rules();
        for f in &disk_files {
            let _ = eng.load_rules(f);
        }
    }
    if eng.get_rules().is_empty() {
        eng.load_default_rules();
    }

    let known_rule_ids: std::collections::HashSet<&str> =
        eng.get_rules().iter().map(|r| r.id.as_str()).collect();

    let mut issues_found = false;

    // Check required_rules
    for rule_id in &policy.required_rules {
        if !known_rule_ids.contains(rule_id.as_str()) {
            eprintln!(
                "sicario: policy validate: unknown rule ID in required_rules: '{}'",
                rule_id
            );
            issues_found = true;
        }
    }

    // Check blocked_suppressions
    for rule_id in &policy.blocked_suppressions {
        if !known_rule_ids.contains(rule_id.as_str()) {
            eprintln!(
                "sicario: policy validate: unknown rule ID in blocked_suppressions: '{}'",
                rule_id
            );
            issues_found = true;
        }
    }

    // Validate glob patterns in scope
    for pattern in &policy.scope {
        if let Err(e) = globset::Glob::new(pattern) {
            eprintln!(
                "sicario: policy validate: invalid glob pattern in scope '{}': {}",
                pattern, e
            );
            issues_found = true;
        }
    }

    if issues_found {
        eprintln!("sicario: policy validate: policy file has issues — fix them before enforcing.");
        Ok(ExitCode::FindingsDetected)
    } else {
        println!("sicario: policy validate: OK — policy file is valid.");
        Ok(ExitCode::Clean)
    }
}

/// `sicario policy init` — generate a `.sicario/policy.yaml` template.
/// Does not overwrite an existing file.
fn cmd_policy_init(args: cli::policy::PolicyInitArgs) -> Result<ExitCode> {
    let project_root = PathBuf::from(&args.dir);
    let sicario_dir = project_root.join(".sicario");
    let policy_path = sicario_dir.join("policy.yaml");

    if policy_path.exists() {
        eprintln!(
            "sicario: policy init: '{}' already exists. Skipping.",
            policy_path.display()
        );
        return Ok(ExitCode::Clean);
    }

    std::fs::create_dir_all(&sicario_dir)?;
    std::fs::write(&policy_path, cli::policy::POLICY_TEMPLATE)?;

    println!("sicario: policy init: created '{}'.", policy_path.display());
    Ok(ExitCode::Clean)
}

fn cmd_fix(args: cli::fix::FixArgs) -> Result<ExitCode> {
    use remediation::agent_selector::{AgentConfig, AgentSelector};
    use remediation::iteration_guard::IterationGuard;
    use remediation::remediation_engine::RemediationEngine;
    use verification::scanner::VerificationScanning;

    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));

    // ── --staged mode ─────────────────────────────────────────────────────────
    if args.staged {
        return cmd_fix_staged(&args, &cwd);
    }

    // Parse --agent flag and resolve effective allow_ai setting.
    // AgentConfig::Local implicitly grants AI consent (localhost calls only).
    let agent_config = match AgentSelector::parse(args.agent.as_deref()) {
        Ok(cfg) => cfg,
        Err(e) => {
            eprintln!("sicario: {e}");
            return Ok(ExitCode::InternalError);
        }
    };
    let effective_allow_ai = args.allow_ai || AgentSelector::implicit_allow_ai(&agent_config);

    // Handle revert
    if let Some(ref patch_id) = args.revert {
        let engine = RemediationEngine::new(&cwd)?;
        engine.revert_by_patch_id(patch_id)?;
        eprintln!("sicario: reverted patch {patch_id}");
        return Ok(ExitCode::Clean);
    }

    // Resolve --max-iterations (also reads SICARIO_MAX_ITERATIONS via clap env)
    let max_iterations = match args.resolve_max_iterations() {
        Ok(n) => n,
        Err(msg) => {
            eprintln!("sicario: {msg}");
            return Ok(ExitCode::InternalError);
        }
    };

    let file_path = PathBuf::from(&args.file);
    if !file_path.exists() {
        eprintln!("sicario fix: file not found: {}", args.file);
        return Ok(ExitCode::InternalError);
    }
    // Resolve to an absolute path without going through canonicalize(), which
    // on Windows produces UNC-prefixed paths (\\?\C:\...) that don't compare
    // equal to the plain absolute paths returned by std::fs::read_dir.
    let file_path = if file_path.is_absolute() {
        file_path
    } else {
        cwd.join(&file_path)
    };
    // Normalise away any `.` or `..` components that were introduced by a
    // `./`-prefixed argument (e.g. `./app/data/user-dao.js`).  We cannot use
    // `canonicalize()` here because on Windows it produces UNC-prefixed paths
    // (`\\?\C:\...`) that don't compare equal to the plain absolute paths
    // returned by `std::fs::read_dir`.
    let file_path = normalize_path(&file_path);

    let is_dir = file_path.is_dir();

    // Scan the file/directory to find vulnerabilities.
    // Use embedded rules (same as cmd_scan) so the full 500+ rule set is active.
    let scan_root = if is_dir {
        file_path.clone()
    } else {
        file_path.parent().unwrap_or(&cwd).to_path_buf()
    };
    let mut eng = engine::sast_engine::SastEngine::new(&cwd)?;
    let embedded_count = load_embedded_rules_into(&mut eng);
    if embedded_count == 0 {
        // Fallback: try disk rules (dev environment)
        for f in discover_bundled_rules() {
            let _ = eng.load_rules(&f);
        }
        if eng.get_rules().is_empty() {
            eng.load_default_rules();
        }
    }
    // For single-file fixes, scan just that file (fast path — avoids SCA and
    // background threads). For directory fixes, scan the whole directory.
    let vulns = if is_dir {
        eng.scan_directory(&scan_root)?
    } else {
        eng.scan_file(&file_path)?
    };

    // Normalise both sides to lowercase strings for a case-insensitive,
    // separator-insensitive comparison (handles Windows drive-letter casing
    // and mixed slash styles).
    let target = file_path
        .to_string_lossy()
        .replace('\\', "/")
        .to_lowercase();

    // Filter to the target file (or all files under the target directory)
    // and optionally the specified rule.
    //
    // For single-file scans, scan_file returns the exact path we passed in,
    // so the comparison is always exact. For directory scans, the engine
    // returns relative paths which we resolve against cwd.
    let file_vulns: Vec<_> = vulns
        .iter()
        .filter(|v| {
            if is_dir {
                // Resolve the vulnerability's file path to absolute
                let abs_vpath = if v.file_path.is_absolute() {
                    v.file_path.clone()
                } else {
                    cwd.join(&v.file_path)
                };
                let vpath = abs_vpath
                    .to_string_lossy()
                    .replace('\\', "/")
                    .to_lowercase();
                // Directory: match any file whose path starts with the target dir
                vpath.starts_with(&target)
            } else {
                // Single-file: scan_file returns the exact path we passed in
                true
            }
        })
        .filter(|v| args.rule.as_ref().is_none_or(|r| v.rule_id == *r))
        .collect();

    if file_vulns.is_empty() {
        eprintln!("sicario fix: no findings in {}", args.file);
        return Ok(ExitCode::Clean);
    }

    let engine = RemediationEngine::new_with_agent(&cwd, &agent_config, effective_allow_ai)?;

    if args.yes {
        // Batch mode: process all vulnerabilities without per-fix prompts
        let rule_files = discover_bundled_rules();
        let batch = engine.generate_and_apply_batch(
            &file_vulns,
            true, // auto_confirm
            args.no_verify,
            &rule_files,
        )?;
        eprintln!(
            "sicario: batch complete — {} applied, {} reverted, {} skipped",
            batch.applied, batch.reverted, batch.skipped
        );
        // ── Task 12.9: Emit PatchReceipt for each successful batch fix ────
        if !args.no_receipt {
            use remediation::remediation_engine::BatchFixOutcome;
            for detail in &batch.details {
                if matches!(detail.outcome, BatchFixOutcome::Applied) {
                    let receipt = remediation::PatchReceipt::deterministic(
                        &detail.rule_id,
                        &*detail.file_path.to_string_lossy(),
                        0, // line not tracked in batch detail
                        0,
                        &detail.rule_id,
                    );
                    receipt.print();
                }
            }
        }
    } else {
        // Interactive mode: confirm each fix individually, with iteration cap
        for vuln in &file_vulns {
            let mut guard = IterationGuard::new(max_iterations, &cwd);
            let fix_start = std::time::Instant::now();
            let patch = loop {
                match engine.generate_patch(vuln) {
                    Ok(p) => break p,
                    Err(e) => {
                        let reason = e.to_string();
                        eprintln!(
                            "sicario: fix attempt {}/{} failed for {} — {reason}",
                            guard.attempts() + 1,
                            max_iterations,
                            vuln.rule_id
                        );
                        if guard.record_failure(reason).is_err() {
                            // Iteration cap reached — log diagnostic and block CI
                            let file_str = vuln.file_path.to_string_lossy();
                            if let Err(log_err) = guard.flush_trace_log(&vuln.rule_id, &file_str) {
                                eprintln!(
                                    "sicario: warning — could not write trace log: {log_err}"
                                );
                            }
                            eprintln!(
                                "sicario: error — could not produce a valid fix for {} in {} \
                                 after {max_iterations} attempt(s). \
                                 Diagnostic written to .sicario/trace.log",
                                vuln.rule_id,
                                vuln.file_path.display()
                            );
                            return Ok(ExitCode::FindingsDetected);
                        }
                    }
                }
            };

            let confirmed = engine.display_diff_and_confirm(&patch)?;
            if confirmed {
                engine.apply_patch(&patch)?;
                let execution_ms = fix_start.elapsed().as_millis();
                eprintln!("sicario: patch applied to {}", args.file);

                // Emit zero-exfiltration receipt (unless suppressed with --no-receipt)
                if !args.no_receipt {
                    let receipt = if let Some(model) = engine.ollama_model_name() {
                        // Local agent path: emit local_agent receipt (zero exfiltration)
                        remediation::PatchReceipt::local_agent(
                            &vuln.rule_id,
                            &args.file,
                            vuln.line as u32,
                            execution_ms,
                            model,
                        )
                    } else {
                        // Deterministic or cloud path
                        remediation::PatchReceipt::deterministic(
                            &vuln.rule_id,
                            &args.file,
                            vuln.line as u32,
                            execution_ms,
                            &vuln.rule_id,
                        )
                    };
                    receipt.print();
                }

                // Open a PR/MR if --pr flag is set
                if args.pr {
                    match engine.create_pull_request(&patch, "auto", &vuln.rule_id) {
                        Ok(pr_url) => {
                            eprintln!("sicario: pull request created: {}", pr_url);
                        }
                        Err(e) => {
                            eprintln!("sicario: warning — could not create pull request: {}", e);
                        }
                    }
                }

                // Post-fix verification
                if !args.no_verify {
                    let mut verifier = verification::VerificationScanner::new(&cwd);
                    let original = verification::OriginalFinding {
                        rule_id: vuln.rule_id.clone(),
                        fingerprint: engine::vulnerability::Finding::compute_fingerprint(
                            &vuln.rule_id,
                            &vuln.file_path,
                            &vuln.snippet,
                        ),
                        file_path: vuln.file_path.clone(),
                    };
                    let rule_files = discover_bundled_rules();
                    match verifier.verify_fix(&file_path, &original, &rule_files)? {
                        verification::VerificationResult::Resolved => {
                            eprintln!("sicario: fix verified — vulnerability resolved");
                        }
                        verification::VerificationResult::StillPresent => {
                            eprintln!("sicario: warning — vulnerability still present after fix");
                        }
                        verification::VerificationResult::NewFindingsIntroduced(new) => {
                            eprintln!(
                                "sicario: warning — fix introduced {} new finding(s)",
                                new.len()
                            );
                        }
                    }
                }
            } else {
                eprintln!("sicario: patch skipped");
            }
        }
    }

    Ok(ExitCode::Clean)
}

// ─── Staged fix command ───────────────────────────────────────────────────────

/// Result of a single staged fix attempt, serialized to JSON with `--format json`.
#[derive(serde::Serialize)]
struct StagedFixResult {
    file: String,
    rule_id: String,
    line: usize,
    fixed: bool,
    template_used: Option<String>,
}

/// Implement `sicario fix --staged`:
///
/// 1. Run `git diff --cached --name-only` to enumerate staged files.
/// 2. Normalize path separators to `/` on Windows.
/// 3. Scan staged files for vulnerabilities.
/// 4. Apply only deterministic (registry) fixes — no LLM fallback.
/// 5. With `--format json`, output a JSON array of fix result objects.
/// 6. Exit non-zero if run outside a Git repository.
fn cmd_fix_staged(args: &cli::fix::FixArgs, cwd: &std::path::Path) -> Result<ExitCode> {
    use cli::fix::FixOutputFormat;
    use remediation::remediation_engine::RemediationEngine;

    // ── Step 1: Enumerate staged files via git ────────────────────────────────
    let git_output = std::process::Command::new("git")
        .args(["diff", "--cached", "--name-only"])
        .current_dir(cwd)
        .output();

    let git_output = match git_output {
        Ok(out) => out,
        Err(e) => {
            eprintln!(
                "sicario fix --staged: failed to run git: {e}\n\
                 Ensure git is installed and this command is run inside a Git repository."
            );
            return Ok(ExitCode::InternalError);
        }
    };

    if !git_output.status.success() {
        let stderr = String::from_utf8_lossy(&git_output.stderr);
        eprintln!(
            "sicario fix --staged: not inside a Git repository or git command failed.\n\
             git error: {stderr}"
        );
        return Ok(ExitCode::InternalError);
    }

    let stdout = String::from_utf8_lossy(&git_output.stdout);
    let staged_files: Vec<String> = stdout
        .lines()
        .filter(|l| !l.is_empty())
        .map(|l| {
            // Normalize path separators to `/` on Windows
            #[cfg(windows)]
            {
                l.replace('\\', "/")
            }
            #[cfg(not(windows))]
            {
                l.to_string()
            }
        })
        .collect();

    if staged_files.is_empty() {
        if args.format == FixOutputFormat::Json {
            println!("[]");
        } else {
            eprintln!("sicario fix --staged: no staged files found");
        }
        return Ok(ExitCode::Clean);
    }

    // ── Step 2: Scan staged files for vulnerabilities ─────────────────────────
    let mut eng = engine::sast_engine::SastEngine::new(cwd)?;
    let embedded_count = load_embedded_rules_into(&mut eng);
    if embedded_count == 0 {
        for f in discover_bundled_rules() {
            let _ = eng.load_rules(&f);
        }
        if eng.get_rules().is_empty() {
            eng.load_default_rules();
        }
    }

    // Collect all vulnerabilities across staged files
    let mut all_vulns: Vec<engine::vulnerability::Vulnerability> = Vec::new();
    for staged_file in &staged_files {
        let file_path = cwd.join(staged_file);
        if !file_path.exists() {
            // File may have been deleted — skip
            continue;
        }
        let parent = file_path.parent().unwrap_or(cwd);
        match eng.scan_directory(parent) {
            Ok(vulns) => {
                let target = file_path
                    .to_string_lossy()
                    .replace('\\', "/")
                    .to_lowercase();
                for v in vulns {
                    let vpath = v
                        .file_path
                        .to_string_lossy()
                        .replace('\\', "/")
                        .to_lowercase();
                    if vpath == target {
                        // Apply optional rule filter
                        if args.rule.as_ref().is_none_or(|r| v.rule_id == *r) {
                            all_vulns.push(v);
                        }
                    }
                }
            }
            Err(e) => {
                tracing::warn!("Failed to scan {}: {}", staged_file, e);
            }
        }
    }

    // ── Step 3: Apply deterministic fixes only (no LLM fallback) ─────────────
    // Use a plain RemediationEngine (allow_ai = false) — the staged path
    // MUST NOT invoke any LLM. Only registry templates are used.
    let engine = RemediationEngine::new(cwd)?;

    let mut results: Vec<StagedFixResult> = Vec::new();

    for vuln in &all_vulns {
        let file_str = vuln.file_path.to_string_lossy().replace('\\', "/");

        // Read original content
        let original_content = match std::fs::read_to_string(&vuln.file_path) {
            Ok(c) => c,
            Err(e) => {
                tracing::warn!("Could not read {}: {}", file_str, e);
                results.push(StagedFixResult {
                    file: file_str,
                    rule_id: vuln.rule_id.clone(),
                    line: vuln.line,
                    fixed: false,
                    template_used: None,
                });
                continue;
            }
        };

        // Try deterministic registry fix only — no LLM
        let fixed_content = engine.try_deterministic_fix(vuln, &original_content);

        match fixed_content {
            Some((content, template_name)) => {
                // Apply the fix
                match std::fs::write(&vuln.file_path, &content) {
                    Ok(()) => {
                        results.push(StagedFixResult {
                            file: file_str,
                            rule_id: vuln.rule_id.clone(),
                            line: vuln.line,
                            fixed: true,
                            template_used: Some(template_name),
                        });
                    }
                    Err(e) => {
                        tracing::warn!("Failed to write fix to {}: {}", file_str, e);
                        results.push(StagedFixResult {
                            file: file_str,
                            rule_id: vuln.rule_id.clone(),
                            line: vuln.line,
                            fixed: false,
                            template_used: None,
                        });
                    }
                }
            }
            None => {
                results.push(StagedFixResult {
                    file: file_str,
                    rule_id: vuln.rule_id.clone(),
                    line: vuln.line,
                    fixed: false,
                    template_used: None,
                });
            }
        }
    }

    // ── Step 4: Output results ────────────────────────────────────────────────
    match args.format {
        FixOutputFormat::Json => {
            println!("{}", serde_json::to_string_pretty(&results)?);
        }
        FixOutputFormat::Text => {
            let fixed_count = results.iter().filter(|r| r.fixed).count();
            let unfixed_count = results.iter().filter(|r| !r.fixed).count();
            for r in &results {
                if r.fixed {
                    eprintln!(
                        "sicario: fixed {} in {}:{} (template: {})",
                        r.rule_id,
                        r.file,
                        r.line,
                        r.template_used.as_deref().unwrap_or("unknown")
                    );
                } else {
                    eprintln!(
                        "sicario: could not fix {} in {}:{} (no deterministic template)",
                        r.rule_id, r.file, r.line
                    );
                }
            }
            eprintln!(
                "sicario fix --staged: {} fixed, {} could not be fixed",
                fixed_count, unfixed_count
            );
        }
    }

    Ok(ExitCode::Clean)
}

// ─── Baseline command ─────────────────────────────────────────────────────────

fn cmd_baseline(args: cli::baseline::BaselineCommand) -> Result<ExitCode> {
    use baseline::manager::{BaselineManagement, BaselineManager};
    use cli::baseline::BaselineAction;

    let cwd = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let mgr = BaselineManager::new(&cwd);

    match args.action {
        BaselineAction::Save(save_args) => {
            // Run a scan to get current findings
            let rule_files = discover_bundled_rules();
            let mut eng = engine::sast_engine::SastEngine::new(&cwd)?;
            for f in &rule_files {
                let _ = eng.load_rules(f);
            }
            let vulns = eng.scan_directory(&cwd)?;
            let findings: Vec<engine::vulnerability::Finding> = vulns
                .iter()
                .map(|v| engine::vulnerability::Finding::from_vulnerability(v, &v.rule_id))
                .collect();

            let path = mgr.save(&findings, save_args.tag.as_deref())?;
            eprintln!("sicario: baseline saved to {}", path.display());
        }
        BaselineAction::Compare(cmp_args) => {
            // Run a scan to get current findings
            let rule_files = discover_bundled_rules();
            let mut eng = engine::sast_engine::SastEngine::new(&cwd)?;
            for f in &rule_files {
                let _ = eng.load_rules(f);
            }
            let vulns = eng.scan_directory(&cwd)?;
            let findings: Vec<engine::vulnerability::Finding> = vulns
                .iter()
                .map(|v| engine::vulnerability::Finding::from_vulnerability(v, &v.rule_id))
                .collect();

            let delta = mgr.compare(&cmp_args.reference, &findings)?;
            if cmp_args.format == "json" {
                println!("{}", serde_json::to_string_pretty(&delta)?);
            } else {
                eprintln!(
                    "New: {}  Resolved: {}  Unchanged: {}",
                    delta.new_findings.len(),
                    delta.resolved_findings.len(),
                    delta.unchanged_findings.len()
                );
            }
        }
        BaselineAction::Trend(trend_args) => {
            let summaries = mgr.trend()?;
            if trend_args.format == "json" {
                println!("{}", serde_json::to_string_pretty(&summaries)?);
            } else {
                for s in &summaries {
                    eprintln!(
                        "{} {}: {} findings (C:{} H:{} M:{} L:{} I:{})",
                        s.timestamp.format("%Y-%m-%d %H:%M"),
                        s.tag.as_deref().unwrap_or("-"),
                        s.total_findings,
                        s.critical_count,
                        s.high_count,
                        s.medium_count,
                        s.low_count,
                        s.info_count,
                    );
                }
            }
        }
        BaselineAction::Diff(diff_args) => {
            return cmd_baseline_diff(diff_args, &cwd, &mgr);
        }
    }

    Ok(ExitCode::Clean)
}

// ─── Baseline diff command ────────────────────────────────────────────────────

fn cmd_baseline_diff(
    args: cli::baseline::BaselineDiffArgs,
    cwd: &std::path::Path,
    mgr: &baseline::manager::BaselineManager,
) -> Result<ExitCode> {
    use baseline::manager::BaselineManagement;
    use engine::vulnerability::Severity;

    // Exit code 2: no baseline file exists
    if !mgr.has_baselines() {
        eprintln!(
            "sicario: no baseline files found in .sicario/baselines/.\n\
             Run `sicario baseline save` to create a baseline before running diff."
        );
        return Ok(ExitCode::InternalError);
    }

    // Run a fresh scan of the current directory
    let rule_files = discover_bundled_rules();
    let mut eng = engine::sast_engine::SastEngine::new(cwd)?;
    for f in &rule_files {
        let _ = eng.load_rules(f);
    }
    let vulns = eng.scan_directory(cwd)?;
    let findings: Vec<engine::vulnerability::Finding> = vulns
        .iter()
        .map(|v| engine::vulnerability::Finding::from_vulnerability(v, &v.rule_id))
        .collect();

    // Resolve the reference: --tag takes precedence over positional reference, then most recent
    let delta = if let Some(tag) = &args.tag {
        mgr.compare(tag, &findings)?
    } else if let Some(reference) = &args.reference {
        mgr.compare(reference, &findings)?
    } else {
        mgr.compare_latest(&findings)?
    };

    let threshold_severity: Severity = args.threshold.into();

    if args.ci {
        // CI mode: print structured summary and exit with appropriate code
        let known = delta.unchanged_findings.len();
        let resolved = delta.resolved_findings.len();
        let new_count = delta.new_findings.len();

        // Count new findings at or above threshold
        let blocking: Vec<&baseline::manager::BaselineFinding> = delta
            .new_findings
            .iter()
            .filter(|f| f.severity >= threshold_severity)
            .collect();

        println!("✓  {} known findings (unchanged — not blocking)", known);
        println!("✓  {} findings resolved since baseline", resolved);

        if blocking.is_empty() {
            println!("✓  {} NEW findings introduced (none blocking)", new_count);
            Ok(ExitCode::Clean)
        } else {
            println!(
                "✗  {} NEW findings introduced (blocking CI)",
                blocking.len()
            );
            println!();
            println!("Blocking new findings:");
            for f in &blocking {
                println!(
                    "  [{severity}] {rule} — {file}:{line}",
                    severity = f.severity,
                    rule = f.rule_id,
                    file = f.file_path.display(),
                    line = f.line,
                );
            }
            // Also list non-blocking new findings if any
            let non_blocking: Vec<&baseline::manager::BaselineFinding> = delta
                .new_findings
                .iter()
                .filter(|f| f.severity < threshold_severity)
                .collect();
            if !non_blocking.is_empty() {
                println!();
                println!("Non-blocking new findings (below threshold):");
                for f in &non_blocking {
                    println!(
                        "  [{severity}] {rule} — {file}:{line}",
                        severity = f.severity,
                        rule = f.rule_id,
                        file = f.file_path.display(),
                        line = f.line,
                    );
                }
            }
            Ok(ExitCode::FindingsDetected)
        }
    } else {
        // Non-CI mode: print delta as JSON
        println!("{}", serde_json::to_string_pretty(&delta)?);
        Ok(ExitCode::Clean)
    }
}

// ─── Config command ───────────────────────────────────────────────────────────

fn cmd_config(args: cli::config::ConfigCommand) -> Result<ExitCode> {
    use cli::config::ConfigAction;

    match args.action {
        ConfigAction::SetKey => {
            eprintln!("Enter your LLM API key: ");
            let mut key = String::new();
            std::io::stdin().read_line(&mut key)?;
            let key = key.trim();
            if key.is_empty() {
                eprintln!("sicario config: no key provided");
                return Ok(ExitCode::Clean);
            }
            key_manager::store_key_in_keyring(key)?;
            eprintln!("sicario: API key stored in OS credential store");
        }
        ConfigAction::Set(set_args) => {
            config::set_global_config_value(&set_args.key, &set_args.value)?;
            let path = config::global_config_path()
                .map(|p| p.display().to_string())
                .unwrap_or_else(|| "~/.sicario/config.toml".to_string());
            eprintln!("sicario: {} saved to {}", set_args.key, path);
            eprintln!("  Note: LLM keys are stored locally and never sent to Sicario Cloud.");
            eprintln!("  SICARIO_API_KEY is separate — it authenticates telemetry uploads only.");
        }
        ConfigAction::SetProvider(provider_args) => {
            use key_manager::{find_provider, PROVIDERS};

            // Determine endpoint and model from either the named preset or explicit flags
            let (endpoint, model, provider_name) = if let Some(ref name) = provider_args.name {
                match find_provider(name) {
                    Some(preset) => {
                        let ep = provider_args
                            .endpoint
                            .clone()
                            .unwrap_or_else(|| preset.endpoint.to_string());
                        let mdl = provider_args
                            .model
                            .clone()
                            .unwrap_or_else(|| preset.default_model.to_string());
                        (ep, mdl, preset.name.to_string())
                    }
                    None => {
                        let valid: Vec<&str> = PROVIDERS.iter().map(|p| p.name).collect();
                        eprintln!(
                            "Unknown provider '{}'. Valid providers: {}",
                            name,
                            valid.join(", ")
                        );
                        return Ok(ExitCode::InternalError);
                    }
                }
            } else if let Some(ref ep) = provider_args.endpoint {
                let mdl = provider_args
                    .model
                    .clone()
                    .unwrap_or_else(|| "gpt-4o-mini".to_string());
                (ep.clone(), mdl, "custom".to_string())
            } else {
                eprintln!("sicario config set-provider: provide a provider name or --endpoint");
                return Ok(ExitCode::InternalError);
            };

            // Write llm_endpoint and llm_model to ~/.sicario/config.toml (global config)
            config::set_global_config_value("llm_endpoint", &endpoint)?;
            config::set_global_config_value("llm_model", &model)?;

            let config_path = config::global_config_path()
                .map(|p| p.display().to_string())
                .unwrap_or_else(|| "~/.sicario/config.toml".to_string());
            eprintln!(
                "Provider set to {}: endpoint={}, model={}",
                provider_name, endpoint, model
            );
            eprintln!("  Written to {}", config_path);
        }
        ConfigAction::Show => {
            use key_manager::PROVIDERS;

            // ── Provider table (all 19 providers) ────────────────────────────
            println!("Supported LLM Providers ({} total):", PROVIDERS.len());
            println!();

            // Compute column widths dynamically for clean alignment
            let name_w = PROVIDERS
                .iter()
                .map(|p| p.name.len())
                .max()
                .unwrap_or(10)
                .max(4);
            let ep_w = 55usize; // truncate long endpoints to keep table readable
            let model_w = PROVIDERS
                .iter()
                .map(|p| {
                    if p.default_model.is_empty() {
                        26
                    } else {
                        p.default_model.len()
                    }
                })
                .max()
                .unwrap_or(13)
                .max(13);
            let envvar_w = PROVIDERS
                .iter()
                .map(|p| {
                    if p.env_var.is_empty() {
                        6
                    } else {
                        p.env_var.len()
                    }
                })
                .max()
                .unwrap_or(7)
                .max(7);

            // Header
            println!(
                "{:<name_w$}  {:<ep_w$}  {:<model_w$}  {:<envvar_w$}",
                "NAME",
                "ENDPOINT",
                "DEFAULT MODEL",
                "ENV VAR",
                name_w = name_w,
                ep_w = ep_w,
                model_w = model_w,
                envvar_w = envvar_w,
            );
            println!(
                "{:-<name_w$}  {:-<ep_w$}  {:-<model_w$}  {:-<envvar_w$}",
                "",
                "",
                "",
                "",
                name_w = name_w,
                ep_w = ep_w,
                model_w = model_w,
                envvar_w = envvar_w,
            );

            for p in PROVIDERS {
                let endpoint_display = if p.endpoint.len() > ep_w {
                    format!("{}…", &p.endpoint[..ep_w - 1])
                } else {
                    p.endpoint.to_string()
                };
                let model_display = if p.default_model.is_empty() {
                    "(local — auto-detected)".to_string()
                } else {
                    p.default_model.to_string()
                };
                let envvar_display = if p.env_var.is_empty() {
                    "(none)".to_string()
                } else {
                    p.env_var.to_string()
                };
                println!(
                    "{:<name_w$}  {:<ep_w$}  {:<model_w$}  {:<envvar_w$}",
                    p.name,
                    endpoint_display,
                    model_display,
                    envvar_display,
                    name_w = name_w,
                    ep_w = ep_w,
                    model_w = model_w,
                    envvar_w = envvar_w,
                );
            }

            // ── Active key source (no network request, no key value) ──────────
            println!();
            let key_source = key_manager::resolve_key_source_no_network();
            let active_label = match &key_source {
                key_manager::KeySource::None => "not configured".to_string(),
                key_manager::KeySource::Keyring => "OS keyring".to_string(),
                key_manager::KeySource::ConfigFile => ".sicario/config.yaml".to_string(),
                other => format!("{} env var", other.label()),
            };
            println!("Active key source: {}", active_label);
            if key_source == key_manager::KeySource::None {
                println!("  Run `sicario config set-key <key>` or set OPENAI_API_KEY / ANTHROPIC_API_KEY.");
            }

            println!();
            println!("Use `sicario config set-provider <name>` to switch providers.");
        }
        ConfigAction::DeleteKey => {
            key_manager::delete_key_from_keyring()?;
            eprintln!("sicario: API key removed from OS credential store");
        }
        ConfigAction::Test => {
            let key = key_manager::resolve_api_key();
            if key.is_none() {
                eprintln!(
                    "sicario config test: no API key configured. Run `sicario config set-key`."
                );
                return Ok(ExitCode::Clean);
            }
            let endpoint = key_manager::resolve_endpoint();
            let model = key_manager::resolve_model();
            eprintln!("Testing connectivity to {endpoint} with model {model}...");
            // Simple connectivity check via reqwest
            let client = reqwest::blocking::Client::builder()
                .timeout(std::time::Duration::from_secs(10))
                .build()?;
            let key = key.unwrap();
            let resp = client
                .post(&endpoint)
                .header("Authorization", format!("Bearer {}", key.key))
                .header("Content-Type", "application/json")
                .body(format!(
                    r#"{{"model":"{}","messages":[{{"role":"user","content":"ping"}}],"max_tokens":1}}"#,
                    model
                ))
                .send();
            match resp {
                Ok(r) if r.status().is_success() => {
                    eprintln!(
                        "sicario: connection successful (key source: {})",
                        key.source.label()
                    );
                }
                Ok(r) => {
                    eprintln!("sicario: server responded with status {}", r.status());
                }
                Err(e) => {
                    eprintln!("sicario: connection failed: {e}");
                }
            }
        }
    }

    Ok(ExitCode::Clean)
}

