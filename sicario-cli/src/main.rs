fn cmd_rules(args: cli::rules::RulesCommand) -> Result<ExitCode> {
    use cli::rules::RulesAction;
    use engine::sast_engine::SastEngine;
    use rule_harness::{RuleQualityValidation, RuleTestHarness};

    let project_root = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let rule_files = discover_bundled_rules();

    // Load all rules
    let mut engine = SastEngine::new(&project_root)?;
    for f in &rule_files {
        if let Err(e) = engine.load_rules(f) {
            eprintln!("warning: could not load {:?}: {e}", f);
        }
    }
    let rules = engine.get_rules().to_vec();
    let harness = RuleTestHarness::new(&project_root);

    match args.action {
        RulesAction::Test(test_args) => {
            eprintln!("Running rule test cases for {} rules...", rules.len());

            // Task 4.4: performance gate — full rule set must complete within 60s
            let start = std::time::Instant::now();
            let report = harness.validate_all(&rules)?;
            let elapsed = start.elapsed();

            // Task 4.3: print "N rules tested, M test cases passed" summary
            let total_cases = report.total_tp_cases + report.total_tn_cases;
            let passed_cases = report.total_tp_passed + report.total_tn_passed;
            let failed_cases = total_cases.saturating_sub(passed_cases);

            if test_args.report {
                if report.aggregate_fp_rate >= 0.15 {
                    eprintln!(
                        "⚠ Aggregate FP rate {:.1}% exceeds 15% threshold",
                        report.aggregate_fp_rate * 100.0
                    );
                }
                println!("{}", serde_json::to_string_pretty(&report)?);
            } else {
                print!("{}", report.display_text());
            }

            // Task 4.4: fail if the run exceeded performance gate
            let max_secs = if cfg!(debug_assertions) { 180 } else { 60 };
            if elapsed.as_secs() > max_secs {
                eprintln!(
                    "[rules test] FAIL: rule set took {:.1}s — exceeds {}-second CI gate.",
                    elapsed.as_secs_f64(),
                    max_secs
                );
                return Ok(ExitCode::InternalError);
            }

            // Task 4.3: print summary line
            if failed_cases > 0 {
                eprintln!(
                    "{} rules tested, {} test cases passed, {} failed ({:.1}s)",
                    rules.len(),
                    passed_cases,
                    failed_cases,
                    elapsed.as_secs_f64()
                );
                // Print per-failure details
                for rule_report in &report.per_rule {
                    for failure in &rule_report.failures {
                        eprintln!(
                            "  FAIL [{}] expected: {} | got: {} | code: {}",
                            rule_report.rule_id,
                            failure.expected,
                            failure.actual,
                            failure.code_snippet
                        );
                    }
                }
                return Ok(ExitCode::FindingsDetected);
            }

            eprintln!(
                "{} rules tested, {} test cases passed ({:.1}s)",
                rules.len(),
                passed_cases,
                elapsed.as_secs_f64()
            );

            if report.invalid_rules > 0 {
                return Ok(ExitCode::FindingsDetected);
            }
        }
        RulesAction::Validate(validate_args) => {
            eprintln!("Validating {} rules...", rules.len());
            let report = harness.validate_all_syntax(&rules);

            if validate_args.report {
                println!("{}", serde_json::to_string_pretty(&report)?);
            } else {
                print!("{}", report.display_text());
            }

            if report.invalid_rules > 0 {
                return Ok(ExitCode::FindingsDetected);
            }
        }
    }

    Ok(ExitCode::Clean)
}

