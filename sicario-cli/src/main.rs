/// `sicario guard scan` — one-shot scan of node_modules
fn cmd_guard_scan(args: cli::guard::GuardScanArgs) -> Result<ExitCode> {
    use guard::behavioral_scanner::BehavioralScanner;
    use guard::quarantine::QuarantineManager;

    let dir = PathBuf::from(&args.dir);
    if !dir.is_dir() {
        eprintln!("sicario: directory does not exist: {}", dir.display());
        return Ok(ExitCode::InternalError);
    }

    // Enumerate all package directories in node_modules/ (top-level only)
    let entries = std::fs::read_dir(&dir)?;
    let mut packages: Vec<PathBuf> = entries
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    packages.sort();

    eprintln!(
        "[sicario guard] Scanning {} packages in {}...",
        packages.len(),
        dir.display()
    );

    let mut critical_count = 0usize;
    let mut high_count = 0usize;
    let mut flagged_packages = Vec::new();

    for pkg_dir in &packages {
        match BehavioralScanner::scan_package(pkg_dir) {
            Ok(anomalies) => {
                let has_critical = anomalies
                    .iter()
                    .any(|a| a.severity == engine::vulnerability::Severity::Critical);
                let has_high = anomalies
                    .iter()
                    .any(|a| a.severity == engine::vulnerability::Severity::High);

                if has_critical || has_high {
                    let pkg_name = pkg_dir
                        .file_name()
                        .and_then(|n| n.to_str())
                        .unwrap_or("unknown");
                    flagged_packages.push((pkg_name.to_string(), anomalies.clone()));

                    if has_critical {
                        critical_count += 1;
                    } else if has_high {
                        high_count += 1;
                    }

                    // Quarantine Critical packages if --auto-quarantine
                    if has_critical && args.auto_quarantine {
                        if let Err(e) = QuarantineManager::quarantine(pkg_dir, &anomalies, true) {
                            eprintln!("[sicario guard] Failed to quarantine {}: {}", pkg_name, e);
                        }
                    }
                }
            }
            Err(e) => {
                tracing::debug!("Failed to scan package {:?}: {}", pkg_dir, e);
            }
        }
    }

    // Print summary table
    if flagged_packages.is_empty() {
        println!("\n[sicario guard] {} packages clean.", packages.len());
        return Ok(ExitCode::Clean);
    }

    println!("\n=== Behavioral Anomalies Detected ===");
    println!("{:<30} {:<10} {:<50}", "Package", "Severity", "Anomaly");
    println!("{}", "-".repeat(90));

    for (pkg_name, anomalies) in &flagged_packages {
        for anomaly in anomalies {
            println!(
                "{:<30} {:<10} {:<50}",
                pkg_name,
                format!("{:?}", anomaly.severity),
                format!(
                    "{:?} at {}:{}",
                    anomaly.signal,
                    anomaly.file.display(),
                    anomaly.line
                )
            );
        }
    }

    println!(
        "\nSummary: {} Critical, {} High",
        critical_count, high_count
    );

    if critical_count > 0 {
        Ok(ExitCode::FindingsDetected)
    } else {
        Ok(ExitCode::Clean)
    }
}

/// `sicario guard ci` — CI mode: scan node_modules/ and site-packages/ with 7 behavioral rules.
/// Exits 1 on any Critical anomaly. Supports --allowlist and --format json.
fn cmd_guard_ci(args: cli::guard::GuardCiArgs) -> Result<ExitCode> {
    use guard::behavioral_scanner::BehavioralScanner;
    use guard::AnomalySignal;

    let project_root = PathBuf::from(&args.dir);

    // Load allowlist if provided
    let allowlist: std::collections::HashSet<String> = if let Some(ref path) = args.allowlist {
        load_guard_allowlist(path)
    } else {
        std::collections::HashSet::new()
    };

    // Directories to scan: node_modules/ packages and site-packages/
    let mut scan_dirs: Vec<(String, PathBuf)> = Vec::new(); // (package_name, path)

    // Node.js: each subdirectory of node_modules/ is a package
    let node_modules = project_root.join("node_modules");
    if node_modules.is_dir() {
        if let Ok(entries) = std::fs::read_dir(&node_modules) {
            for entry in entries.filter_map(|e| e.ok()) {
                let name = entry.file_name().to_string_lossy().to_string();
                if entry.path().is_dir() && !name.starts_with('.') {
                    scan_dirs.push((name, entry.path()));
                }
            }
        }
    }

    // Python: site-packages/ — each subdirectory is a package
    for venv_dir in &["venv", ".venv", "env", ".env"] {
        let lib = project_root.join(venv_dir).join("lib");
        if lib.is_dir() {
            if let Ok(py_entries) = std::fs::read_dir(&lib) {
                for py_entry in py_entries.filter_map(|e| e.ok()) {
                    let sp = py_entry.path().join("site-packages");
                    if sp.is_dir() {
                        if let Ok(pkg_entries) = std::fs::read_dir(&sp) {
                            for pkg in pkg_entries.filter_map(|e| e.ok()) {
                                let name = pkg.file_name().to_string_lossy().to_string();
                                if pkg.path().is_dir() && !name.ends_with(".dist-info") {
                                    scan_dirs.push((name, pkg.path()));
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    if scan_dirs.is_empty() {
        eprintln!("[guard ci] No packages found in node_modules/ or site-packages/");
        return Ok(ExitCode::Clean);
    }

    let mut all_critical = 0usize;
    let mut all_high = 0usize;

    #[derive(serde::Serialize)]
    struct GuardFinding {
        package: String,
        anomaly_type: String,
        severity: String,
        file: String,
        line: usize,
        snippet: String,
    }
    let mut json_findings: Vec<GuardFinding> = Vec::new();

    for (pkg_name, pkg_path) in &scan_dirs {
        if allowlist.contains(pkg_name) {
            continue;
        }

        let anomalies = match BehavioralScanner::scan_package(pkg_path) {
            Ok(a) => a,
            Err(_) => continue,
        };

        for anomaly in &anomalies {
            let is_critical = anomaly.severity == crate::engine::vulnerability::Severity::Critical;
            let severity_str = if is_critical { "Critical" } else { "High" };
            let anomaly_type = format!("{:?}", anomaly.signal);

            if is_critical {
                all_critical += 1;
            } else {
                all_high += 1;
            }

            if args.format == "json" {
                json_findings.push(GuardFinding {
                    package: pkg_name.clone(),
                    anomaly_type,
                    severity: severity_str.to_string(),
                    file: anomaly.file.to_string_lossy().to_string(),
                    line: anomaly.line,
                    snippet: anomaly.snippet.clone(),
                });
            } else {
                eprintln!(
                    "[guard ci] {} {} — {:?} ({}:{})",
                    severity_str,
                    pkg_name,
                    anomaly.signal,
                    anomaly.file.display(),
                    anomaly.line
                );
                if is_critical {
                    eprintln!("  snippet: {}", anomaly.snippet);
                }
            }
        }
    }

    if args.format == "json" {
        println!("{}", serde_json::to_string_pretty(&json_findings)?);
        if all_critical > 0 {
            eprintln!(
                "[guard ci] FAIL: {} Critical anomaly(ies) found",
                all_critical
            );
        }
    } else {
        eprintln!(
            "[guard ci] Summary: {} Critical, {} High",
            all_critical, all_high
        );
    }

    if all_critical > 0 {
        Ok(ExitCode::FindingsDetected)
    } else {
        Ok(ExitCode::Clean)
    }
}

/// `sicario guard install <package>` — wrap npm/pip install, scan new package, block if Critical.
fn cmd_guard_install(args: cli::guard::GuardInstallArgs) -> Result<ExitCode> {
    use guard::behavioral_scanner::BehavioralScanner;

    let project_root = PathBuf::from(&args.dir);
    let allowlist: std::collections::HashSet<String> = if let Some(ref path) = args.allowlist {
        load_guard_allowlist(path)
    } else {
        std::collections::HashSet::new()
    };

    if allowlist.contains(&args.package) {
        eprintln!(
            "[guard install] {} is in allowlist — installing without scan",
            args.package
        );
    }

    // Snapshot pre-install state
    let node_modules = project_root.join("node_modules");
    let pre_install_packages: std::collections::HashSet<String> = if node_modules.is_dir() {
        std::fs::read_dir(&node_modules)
            .map(|entries| {
                entries
                    .filter_map(|e| e.ok())
                    .filter_map(|e| e.file_name().into_string().ok())
                    .collect()
            })
            .unwrap_or_default()
    } else {
        std::collections::HashSet::new()
    };

    // Run the actual install
    eprintln!(
        "[guard install] Installing {} via {}…",
        args.package, args.pm
    );
    let install_status = match args.pm.as_str() {
        "pip" => std::process::Command::new("pip")
            .args(["install", &args.package])
            .current_dir(&project_root)
            .status(),
        _ => std::process::Command::new("npm")
            .args(["install", &args.package])
            .current_dir(&project_root)
            .status(),
    };

    match install_status {
        Ok(s) if !s.success() => {
            eprintln!(
                "[guard install] Install failed with exit code {:?}",
                s.code()
            );
            return Ok(ExitCode::InternalError);
        }
        Err(e) => {
            eprintln!("[guard install] Could not run {}: {e}", args.pm);
            return Ok(ExitCode::InternalError);
        }
        _ => {}
    }

    // Scan newly installed packages
    if !allowlist.contains(&args.package) && node_modules.is_dir() {
        let new_packages: Vec<PathBuf> = std::fs::read_dir(&node_modules)
            .map(|entries| {
                entries
                    .filter_map(|e| e.ok())
                    .filter(|e| {
                        let name = e.file_name().into_string().unwrap_or_default();
                        !pre_install_packages.contains(&name)
                    })
                    .map(|e| e.path())
                    .collect()
            })
            .unwrap_or_default();

        for pkg_path in &new_packages {
            let anomalies = BehavioralScanner::scan_package(pkg_path)?;
            let critical: Vec<_> = anomalies
                .iter()
                .filter(|a| a.severity == crate::engine::vulnerability::Severity::Critical)
                .collect();

            if !critical.is_empty() {
                eprintln!(
                    "[guard install] BLOCKED: {} has {} Critical anomaly(ies) — removing",
                    pkg_path.display(),
                    critical.len()
                );
                for a in &critical {
                    eprintln!(
                        "  Critical — {:?} ({}:{})",
                        a.signal,
                        a.file.display(),
                        a.line
                    );
                }
                // Restore: remove the newly installed package
                if let Err(e) = std::fs::remove_dir_all(pkg_path) {
                    eprintln!(
                        "[guard install] warning: could not remove {}: {e}",
                        pkg_path.display()
                    );
                }
                return Ok(ExitCode::FindingsDetected);
            }
        }
    }

    eprintln!(
        "[guard install] {} installed and scanned — no Critical anomalies found",
        args.package
    );
    Ok(ExitCode::Clean)
}

/// Load a YAML allowlist of known-safe package names.
fn load_guard_allowlist(path: &str) -> std::collections::HashSet<String> {
    let content = match std::fs::read_to_string(path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[guard] warning: could not read allowlist {path}: {e}");
            return std::collections::HashSet::new();
        }
    };
    // Simple YAML list: each line is "- package-name"
    content
        .lines()
        .map(|l| l.trim().trim_start_matches('-').trim().to_string())
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect()
}

/// `sicario guard watch` — persistent mode
fn cmd_guard_watch(args: cli::guard::GuardWatchArgs) -> Result<ExitCode> {
    use guard::watcher::{resolve_npm_cache_dir, PackageWatcher};

    let project_root = PathBuf::from(&args.project);

    // Resolve the cache directory based on the package manager
    let cache_dir = match args.pm.as_str() {
        "npm" => resolve_npm_cache_dir(&project_root),
        "pip" | "cargo" => {
            eprintln!(
                "sicario: --pm {} is not yet supported. Only npm is supported.",
                args.pm
            );
            return Ok(ExitCode::InternalError);
        }
        _ => {
            eprintln!(
                "sicario: unknown package manager '{}'. Supported: npm, pip, cargo",
                args.pm
            );
            return Ok(ExitCode::InternalError);
        }
    };

    let cache_dir = match cache_dir {
        Some(d) => d,
        None => {
            eprintln!("sicario: could not resolve package cache directory for {}. Ensure node_modules/ exists.", args.pm);
            return Ok(ExitCode::InternalError);
        }
    };

    PackageWatcher::watch(&cache_dir, &project_root, args.auto_quarantine)?;
    Ok(ExitCode::Clean)
}

/// `sicario guard list` — list all quarantined packages
fn cmd_guard_list() -> Result<ExitCode> {
    use guard::quarantine::QuarantineManager;

    let project_root = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let records = QuarantineManager::list(&project_root)?;

    if records.is_empty() {
        println!("No packages quarantined.");
        return Ok(ExitCode::Clean);
    }

    println!("=== Quarantined Packages ===");
    println!(
        "{:<30} {:<10} {:<20} {:<10}",
        "Package", "Version", "Quarantined At", "Action"
    );
    println!("{}", "-".repeat(70));

    for record in &records {
        println!(
            "{:<30} {:<10} {:<20} {:<10}",
            record.package_name,
            record.version,
            record.quarantined_at.chars().take(19).collect::<String>(),
            format!("{:?}", record.action)
        );
    }

    println!("\nTotal: {} packages", records.len());
    Ok(ExitCode::Clean)
}

/// `sicario guard restore` — restore a quarantined package
fn cmd_guard_restore(args: cli::guard::GuardRestoreArgs) -> Result<ExitCode> {
    let project_root = std::env::current_dir().unwrap_or_else(|_| PathBuf::from("."));
    let node_modules = project_root.join("node_modules");

    let quarantined_path = node_modules.join(format!("{}.sicario-quarantined", args.package_name));
    let restored_path = node_modules.join(&args.package_name);

    if !quarantined_path.exists() {
        eprintln!(
            "sicario: quarantined package not found: {}",
            quarantined_path.display()
        );
        return Ok(ExitCode::InternalError);
    }

    std::fs::rename(&quarantined_path, &restored_path)?;
    println!("Restored package: {}", args.package_name);
    Ok(ExitCode::Clean)
}

